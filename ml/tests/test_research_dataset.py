T0 = datetime(2026, 11, 2, 9, 0, tzinfo=timezone.utc)
iso = lambda t: t.isoformat()  # noqa: E731


def make_dataset(people=6, sessions_each=2, studies=('S1',), seed=0, scopes='collection|research_analysis|commercial_model_training'):
    """Synthetic, internally coherent dataset. Gas volumes come from an
    arbitrary rule chosen only so that the arithmetic is checkable."""
    rng = np.random.default_rng(seed)
    t = {k: [] for k in TABLES}
    for st in studies:
        t['studies'].append(dict(study_id=st, site=f'site-{st}', protocol_version='1.0', ethics_reference='SYNTH-0', licence='test', is_synthetic=1))
    t['devices'] += [dict(device_id='CART', tier='criterion_portable', make_model='synthetic analyser'),
                     dict(device_id='WATCH', tier='wearable_estimate', make_model='synthetic watch')]
    n = 0
    for st in studies:
        for i in range(people):
            pid = f'P-{st}{i:05d}'
            sex = 'female' if i % 2 else 'male'
            person_effect = 1 + 0.15 * rng.standard_normal()
            t['participants'].append(dict(participant_id=pid, study_id=st, cross_study_key=f'K{st}{i}', age_years=int(rng.integers(18, 70)), sex=sex,
                                          height_cm=float(rng.integers(150, 200)), training_status='trained'))
            t['consents'].append(dict(participant_id=pid, study_id=st, consent_version='1', consented_at='2026-10-01', scopes=scopes, withdrawn_at=None))
            for k in range(sessions_each):
                n += 1
                sid = f'SES{n:04d}'
                start = T0 + timedelta(days=n)
                cursor, rows = start, []
                nsets = int(rng.integers(8, 16))
                for j in range(nsets):
                    a = cursor
                    b = a + timedelta(seconds=40)
                    cat = ('compound_lower', 'isolation_upper', 'isolation_lower')[int(rng.integers(0, 3))]
                    rows.append(dict(session_id=sid, set_index=j + 1, exercise_name=cat, exercise_category=cat, is_warmup=0,
                                     reps=int(rng.integers(5, 15)), load_kg=float(rng.integers(10, 100)), set_started_at=iso(a), set_ended_at=iso(b)))
                    cursor = b + timedelta(seconds=int(rng.integers(60, 150)))
                end = b
                t['sets'] += rows
                mass = float(rng.integers(50, 120))
                t['sessions'].append(dict(session_id=sid, study_id=st, participant_id=pid, session_date=start.date().isoformat(),
                                          body_mass_kg=mass, session_kind='straight_sets', started_at=iso(start), ended_at=iso(end),
                                          session_rpe=5 + (k % 3)))
                minutes = (end - start).total_seconds() / 60
                vo2 = 0.012 * mass * minutes * person_effect * (1 + 0.1 * rng.standard_normal())
                vco2 = vo2 * 0.9
                rest_a = start - timedelta(minutes=15)
                t['measurements'] += [
                    dict(measurement_id=f'M{sid}R', session_id=sid, device_id='CART', tier='criterion_portable', interval='resting_baseline',
                         interval_start=iso(rest_a), interval_end=iso(rest_a + timedelta(minutes=10)), vo2_l=0.0036 * mass * 10,
                         vco2_l=0.0036 * mass * 10 * 0.82, calibrated_at=iso(rest_a - timedelta(minutes=30)), qc_status='pass'),
                    dict(measurement_id=f'M{sid}S', session_id=sid, device_id='CART', tier='criterion_portable', interval='session',
                         interval_start=iso(start), interval_end=iso(end), vo2_l=vo2, vco2_l=vco2,
                         gross_kcal=gross_kcal_from_gas(vo2, vco2), calibrated_at=iso(rest_a - timedelta(minutes=30)), qc_status='pass'),
                    dict(measurement_id=f'M{sid}W', session_id=sid, device_id='WATCH', tier='wearable_estimate', interval='session',
                         interval_start=iso(start), interval_end=iso(end), gross_kcal=300.0, reported_kcal_kind='net_active', qc_status='not_checked'),
                ]
    return {k: pd.DataFrame(v, columns=template_header(k)) for k, v in t.items()}


def rules(issues):
    return {i.rule for i in errors(issues)}


class ValidationTests(unittest.TestCase):
    def test_coherent_dataset_has_no_errors(self):
        ds = make_dataset()
        self.assertEqual(errors(validate(ds)), [])

    def test_direct_identifier_column_rejected(self):
        ds = make_dataset()
        ds['participants']['email'] = 'x@y.z'
        self.assertIn('direct_identifier', rules(validate(ds)))

    def test_pseudonym_must_be_a_random_code(self):
        ds = make_dataset()
        ds['participants'].loc[0, 'participant_id'] = 'Jane Smith'
        self.assertIn('pseudonym_format', rules(validate(ds)))

    def test_missing_or_withdrawn_consent_excludes_participant(self):
        ds = make_dataset()
        pid = ds['participants'].loc[0, 'participant_id']
        ds['consents'].loc[ds['consents']['participant_id'] == pid, 'withdrawn_at'] = '2026-11-20'
        issues = validate(ds)
        self.assertIn('consent_withdrawn', rules(issues))
        table = build_session_table(ds, issues)
        self.assertNotIn(pid, set(table['participant_id']))

    def test_training_use_needs_its_own_consent_scope(self):
        ds = make_dataset(scopes='collection|research_analysis')
        self.assertEqual(eligible_participants(ds, 'training'), set())
        self.assertEqual(len(eligible_participants(ds, 'research')), 6)
        self.assertEqual(len(build_session_table(ds, validate(ds), use='training')), 0)

    def test_set_timing_rules(self):
        ds = make_dataset()
        s = ds['sets']
        first = s.index[0]
        s.loc[s.index[1], 'set_started_at'] = s.loc[first, 'set_started_at']   # overlap
        s.loc[s.index[2], 'reps'] = 200                                          # 200 reps in 40 s
        self.assertTrue({'overlapping_sets', 'rep_speed'} <= rules(validate(ds)))

    def test_set_outside_session_window(self):
        ds = make_dataset()
        ds['sets'].loc[0, 'set_started_at'] = iso(T0 - timedelta(days=30))
        self.assertIn('outside_session', rules(validate(ds)))

    def test_criterion_measurement_rules(self):
        ds = make_dataset()
        m = ds['measurements']
        sess = m.index[(m['interval'] == 'session') & (m['tier'] == 'criterion_portable')]
        m.loc[sess[0], 'calibrated_at'] = None
        m.loc[sess[1], 'vco2_l'] = m.loc[sess[1], 'vo2_l'] * 2          # RER 2.0
        m.loc[sess[2], 'gross_kcal'] = 9999                            # disagrees with Weir
        m.loc[sess[3], 'interval_end'] = m.loc[sess[3], 'interval_start'][:-6] + '+00:00'  # same instant
        found = rules(validate(ds))
        self.assertTrue({'calibration', 'rer', 'weir_mismatch', 'interval_order'} <= found, found)

    def test_partial_session_coverage_is_not_ground_truth(self):
        ds = make_dataset()
        m = ds['measurements']
        i = m.index[(m['interval'] == 'session') & (m['tier'] == 'criterion_portable')][0]
        m.loc[i, 'interval_end'] = iso(pd.to_datetime(m.loc[i, 'interval_start']) + timedelta(minutes=2))
        self.assertIn('partial_coverage', rules(validate(ds)))

    def test_wearable_figure_must_declare_gross_or_net(self):
        ds = make_dataset()
        m = ds['measurements']
        m.loc[m['tier'] == 'wearable_estimate', 'reported_kcal_kind'] = None
        self.assertIn('kcal_kind', rules(validate(ds)))

    def test_device_tier_must_match(self):
        ds = make_dataset()
        m = ds['measurements']
        m.loc[m['tier'] == 'wearable_estimate', 'tier'] = 'criterion_lab'
        self.assertIn('tier_mismatch', rules(validate(ds)))


class EnergyAndFeatureTests(unittest.TestCase):
    def test_weir(self):
        self.assertAlmostEqual(gross_kcal_from_gas(10, 8), 3.941 * 10 + 1.106 * 8)
        with self.assertRaises(ValueError):
            gross_kcal_from_gas(10, None)

    def test_net_records_where_resting_came_from(self):
        self.assertEqual(net_kcal(300, 60, resting_kcal_per_min=1.2), (300 - 72, 'measured'))
        self.assertEqual(net_kcal(300, 60, predicted_resting_kcal_per_min=1.0)[1], 'predicted')
        self.assertEqual(net_kcal(300, 60), (None, None))

    def test_session_table_separates_work_rest_and_density(self):
        ds = make_dataset(people=1, sessions_each=1)
        table = build_session_table(ds, validate(ds))
        r = table.iloc[0]
        sets = ds['sets']
        self.assertEqual(r['sets'], len(sets))
        self.assertAlmostEqual(r['work_min'], len(sets) * 40 / 60)
        self.assertAlmostEqual(r['work_min'] + r['rest_min'], r['duration_min'])
        self.assertAlmostEqual(r['sets_per_min'], len(sets) / r['duration_min'])
        self.assertEqual(r['resting_source'], 'measured')
        self.assertEqual(r['criterion_tier'], 'criterion_portable')
        self.assertEqual(r['wearable_estimate_kcal'], 300.0, 'wearable kept as a comparison column')
        self.assertEqual(r['wearable_estimate_kind'], 'net_active')
        self.assertNotEqual(r['target_net_kcal'], 300.0, 'the target is never the wearable figure')

    def test_failed_qc_gives_no_target(self):
        ds = make_dataset(people=1, sessions_each=1)
        ds['measurements'].loc[ds['measurements']['tier'] == 'criterion_portable', 'qc_status'] = 'fail'
        table = build_session_table(ds, validate(ds))
        self.assertTrue(table['target_net_kcal'].isna().all())


class QualityAndSplitTests(unittest.TestCase):
    def test_report_never_counts_synthetic_sessions_as_evidence(self):
        ds = make_dataset()
        issues = validate(ds)
        rep = quality_report(ds, issues, build_session_table(ds, issues))
        self.assertEqual(rep['sessions_with_criterion_target'], 0)
        self.assertEqual(rep['independent_people'], 0)
        self.assertEqual(rep['synthetic_sessions_excluded'], 12)
        self.assertIn('participants', rep['missingness'])

    def test_same_person_in_two_studies_is_one_person(self):
        ds = make_dataset(studies=('S1', 'S2'))
        ds['participants']['cross_study_key'] = ds['participants']['participant_id'].str[-5:]  # same people in S1 and S2
        ds['studies']['is_synthetic'] = 0  # count them, for this check only
        issues = validate(ds)
        table = build_session_table(ds, issues)
        rep = quality_report(ds, issues, table)
        self.assertEqual(rep['independent_people'], 6)
        self.assertEqual(rep['participant_ids'], 12)
        self.assertEqual(rep['people_in_more_than_one_study'], 6)
        for study, tr, te in leave_one_study_out(table):
            self.assertEqual(len(tr), 0, 'everyone also appears in the held-out study, so nobody may train')

    def test_person_folds_never_leak(self):
        ds = make_dataset(people=10, sessions_each=3)
        table = build_session_table(ds, validate(ds))
        seen = set()
        for tr, te in person_folds(table, k=5):
            self.assertFalse(set(table.loc[tr, 'person_key']) & set(table.loc[te, 'person_key']))
            seen |= set(te)
        self.assertEqual(seen, set(table.index))
        with self.assertRaises(LeakageError):
            assert_no_leakage(table.iloc[:4], table.iloc[3:6])

    def test_psi(self):
        rng = np.random.default_rng(1)
        a = rng.normal(0, 1, 2000)
        self.assertLess(psi(a, rng.normal(0, 1, 2000)), 0.1)
        self.assertGreater(psi(a, rng.normal(1.5, 1, 2000)), 0.25)
        shift = distribution_shift(pd.DataFrame({'age_years': a * 5 + 30}), pd.DataFrame({'age_years': a * 5 + 45}))
        self.assertEqual(shift['age_years']['level'], 'large')


class GateTests(unittest.TestCase):
    def test_synthetic_data_never_opens_a_gate(self):
        ds = make_dataset(people=40, sessions_each=6, studies=('S1', 'S2', 'S3'))
        table = build_session_table(ds, validate(ds))
        for level in ('baseline_calibration', 'model_comparison', 'tree_models'):
            self.assertFalse(check_gate(table, level).passed)
        res = evaluate(table)
        self.assertTrue(all(not r['ran'] for r in res.values()))

    def test_harness_runs_on_synthetic_only_when_asked_and_marks_it_non_evidence(self):
        ds = make_dataset(people=40, sessions_each=6, studies=('S1', 'S2', 'S3'))
        table = build_session_table(ds, validate(ds))
        res = evaluate(table, allow_synthetic=True)
        self.assertTrue(res['production_baseline']['ran'])
        self.assertFalse(res['production_baseline']['evidence'])
        self.assertTrue(res['calibrated_baseline']['ran'])
        self.assertTrue(res['hierarchical_regression']['ran'])
        self.assertEqual(res['hierarchical_regression']['person_cv']['n'], len(table))
        self.assertFalse(res['gradient_boosting']['ran'], '120 people is below the tree-model gate')
        self.assertIn('people', ' '.join(res['gradient_boosting']['shortfalls']))
        self.assertEqual(set(res['production_baseline']['leave_one_study_out']), {'S1', 'S2', 'S3'})


class TemplateTests(unittest.TestCase):
    def test_templates_round_trip(self):
        with tempfile.TemporaryDirectory() as d:
            for table in TABLES:
                pd.DataFrame(columns=template_header(table)).to_csv(os.path.join(d, f'{table}.csv'), index=False)
            ds = load_dataset(d)
            self.assertEqual(set(ds), set(TABLES))
            self.assertEqual(list(ds['sets'].columns), template_header('sets'))


